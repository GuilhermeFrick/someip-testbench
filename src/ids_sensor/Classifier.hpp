namespace ids
{

/**
 * @brief Abstract inference engine.
 */
class IClassifier
{
  public:
    /**
     * @brief Virtual destructor.
     * @return None.
     */
    virtual ~IClassifier() = default;

    /**
     * @brief Classify ONE already normalised feature vector.
     * @param[in]  x   Normalised feature vector.
     * @param[out] out Per-class probabilities.
     * @return None.
     * @warning Does not allocate.
     */
    virtual void Predict(const FeatureVec &x, ProbVec &out) const = 0;

    /**
     * @brief Engine name, as it appears in the reported metrics.
     * @return Stable, null-terminated engine identifier.
     */
    [[nodiscard]] virtual const char *Name() const = 0;
};

/**
 * @brief Pick the most probable class.
 * @param[in] probabilities Per-class probabilities.
 * @return Class holding the highest probability; the first one on a tie.
 */
[[nodiscard]] TrafficClass ArgMax(const ProbVec &probabilities);

/**
 * @brief Production engine: C99 generated by TL2cgen, compiled into the build of the selected
 *        model, with no runtime dependency.
 * @details Measured at 1,39 us per prediction with the adopted model, which makes it the fastest
 *          of the three engines evaluated. See experiments/bench-inference/RESULTADOS.md.
 */
class Tl2cgenClassifier final : public IClassifier
{
  public:
    /**
     * @brief Bind to the model compiled into this build.
     * @return None.
     */
    Tl2cgenClassifier();

    /**
     * @copydoc ::ids::IClassifier::Predict(const FeatureVec &, ProbVec &) const
     */
    void Predict(const FeatureVec &x, ProbVec &out) const override;

    /**
     * @copydoc ::ids::IClassifier::Name() const
     */
    [[nodiscard]] const char *Name() const override
    {
        return "tl2cgen";
    }
};

/**
 * @brief Parity oracle: the model as tables walked by a bounded loop.
 * @details Slower than TL2cgen with the adopted model, so it stays off the hot path. It is kept
 *          because it has exact parity against the Python reference and a worst case execution
 *          time bounded by construction, which makes it an independent second oracle. It was the
 *          cross check against this evaluator that revealed the model @c base_score is a
 *          per-class vector rather than a scalar.
 * @warning PENDING before it can be promoted to the hot path: handle the XGBoost @c missing
 *          direction. The current prototype always compares, which only happened not to diverge
 *          because the data contains no NaN.
 */
class CompactClassifier final : public IClassifier
{
  public:
    /**
     * @brief Load the node tables.
     * @param[in] tablesPath Path to the exported node-table artefact.
     * @return None.
     * @details The model is DATA here, so changing model does not require recompiling.
     */
    explicit CompactClassifier(const std::string &tablesPath);

    /**
     * @brief Release the node tables.
     * @return None.
     */
    ~CompactClassifier() override;

    /**
     * @copydoc ::ids::IClassifier::Predict(const FeatureVec &, ProbVec &) const
     */
    void Predict(const FeatureVec &x, ProbVec &out) const override;

    /**
     * @copydoc ::ids::IClassifier::Name() const
     */
    [[nodiscard]] const char *Name() const override
    {
        return "compacto";
    }

  private:
    struct Impl;                  ///< Node tables, kept out of this header.
    std::unique_ptr<Impl> m_impl; ///< Owned node tables.
};

} // namespace ids

