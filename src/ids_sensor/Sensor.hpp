/**
 * @file      Sensor.hpp
 * @author    Guilherme Frick (frickoliveira.ee@gmail.com)
 * @brief     Composition root of the ids_sensor component: chains the four pipeline stages and
 *            times each one.
 * @version   2.0
 * @date      2026-10-31
 * @copyright Copyright (c) 2026
 *
 * @details   This is the only class @c main() needs to see. The sensor implements none of the
 *            pipeline itself; it chains the stages and measures them. Splitting it into four
 *            stages is deliberate: it is the same cost decomposition that is reported in the paper
 *            (layer, feature, classification, decision), so the instrumentation falls on the same
 *            points with no translation.
 *
 * @details   Component Guide
 * ============================
 * How to build this component
 * ============================
 * The component is header plus source under @c src/ids_sensor, built as one library and linked
 * into the node executable. It needs:
 *  - a C++14 toolchain, per the AUTOSAR C++14 guidelines. The component also builds unchanged with
 *    @c -std=c++17;
 *  - @c src/ara, the bench subset of the Adaptive Platform types this component uses. On a real
 *    Adaptive Platform, delete that directory and point the includes at the vendor stack;
 *  - @c libpcap, for ::ids::PcapSource and ::ids::LiveSource;
 *  - the C99 translation unit generated by TL2cgen for the selected model, compiled alongside,
 *    when ::ids::Tl2cgenClassifier is used.
 *
 * Three artefacts must come from the SAME training run and be embedded together: the tree model,
 * the byte-model tables and the normalisation bounds. Mixing runs shifts the decision boundary
 * without raising any error, which is why ::ids::IdsSensorErrc::TrainingRunMismatch exists.
 *
 * ============================
 * How to use this component
 * ============================
 * Every stage that can fail is built through a @c Create() returning ara::core::Result, so a
 * sensor that was constructed is a sensor whose stages are all usable. Wire them together and hand
 * the sensor a packet source. The same call serves PCAP replay and live capture, because the
 * source is an interface.
 *
 * @code
 * auto models = ids::ByteModels::Create("artefacts/bytemodels.bin");
 * auto norm   = ids::Normalizer::Create("artefacts/minmax.bin");
 * if (!models.HasValue() || !norm.HasValue())
 * {
 *     // models.Error().Message() says which artefact, and why.
 *     return;
 * }
 *
 * const ids::StreamerConfig cfg;
 * auto streamer = ids::FeatureStreamer::Create(models.Value(), cfg);
 * auto clf      = ids::Tl2cgenClassifier::Create();
 * auto sink     = ids::IdsmDispatcher::Create("ids_sensor/SecurityEvents");
 * auto source   = ids::PcapSource::Create("captures/benign.pcap");
 * if (!streamer.HasValue() || !clf.HasValue() || !sink.HasValue() || !source.HasValue())
 * {
 *     return;
 * }
 *
 * ids::SomeipParser parser;
 * ids::Sensor       sensor(parser, *streamer.Value(), norm.Value(), *clf.Value(), *sink.Value());
 * sensor.Run(*source.Value());
 *
 * const ids::StageTiming &t = sensor.Timing();
 * // t.parseUs, t.featureUs, t.classifyUs, t.decideUs, t.packets, t.events
 * @endcode
 */
#pragma once

#include <cstdint>

#include "src/ids_sensor/Classifier.hpp"
#include "src/ids_sensor/FeatureStreamer.hpp"
#include "src/ids_sensor/Normalizer.hpp"
#include "src/ids_sensor/PacketSource.hpp"
#include "src/ids_sensor/SecurityEventDispatcher.hpp"
#include "src/ids_sensor/SomeipParser.hpp"
#include "src/ids_sensor/types.hpp"

/** @addtogroup IdsSensorSensor Sensor composition
 *  @ingroup IdsSensor
 *  @{
 */

namespace ids
{

/**
 * @brief Accumulated time per pipeline stage, in microseconds.
 */
struct StageTiming
{
    double        parseUs    = 0.0; ///< Time spent in layered parsing.
    double        featureUs  = 0.0; ///< Time spent extracting features.
    double        classifyUs = 0.0; ///< Time spent in inference.
    double        decideUs   = 0.0; ///< Time spent deciding and reporting.
    std::uint64_t packets    = 0U;  ///< Packets processed.
    std::uint64_t malformed  = 0U;  ///< Frames the parser rejected.
    std::uint64_t events     = 0U;  ///< Security events reported.
};

/**
 * @brief Chains parser, extractor, normaliser, classifier and event dispatcher.
 */
class Sensor final
{
  public:
    /**
     * @brief Wire the pipeline stages together.
     * @param[in] parser   Layered packet decoder.
     * @param[in] streamer Feature extractor, which carries the window state.
     * @param[in] norm     Normalisation bounds from training.
     * @param[in] clf      Inference engine to use.
     * @param[in] sink     Destination of the security events.
     * @return None.
     * @details Dependencies enter by reference: whoever builds the sensor decides which engine and
     *          which event sink to use. The sensor chooses neither, and owns neither.
     * @warning Every referenced stage must outlive the sensor.
     */
    Sensor(SomeipParser &parser, FeatureStreamer &streamer, const Normalizer &norm, const IClassifier &clf, ISecurityEventDispatcher &sink);

    /**
     * @brief Process one frame end to end.
     * @param[in] frame Raw frame to process.
     * @return None.
     * @details Parses, extracts, normalises, infers and, when the predicted class raises an event,
     *          dispatches it. Updates the stage timings. A frame the parser rejects is counted in
     *          ::ids::StageTiming::malformed and costs only the parse stage, which is why a capture
     *          full of non-SOME/IP traffic does not distort the other three averages.
     */
    void OnFrame(const Frame &frame);

    /**
     * @brief Consume a source until the end of its stream.
     * @param[in] source Packet source to drain.
     * @return None.
     * @details The SAME function serves PCAP replay and live capture, because the source is an
     *          interface.
     */
    void Run(IPacketSource &source);

    /**
     * @brief Accumulated stage timings.
     * @return Timings collected since construction or since the last ResetTiming().
     */
    const StageTiming &Timing() const noexcept
    {
        return m_timing;
    }

    /**
     * @brief Zero the accumulated stage timings.
     * @return None.
     */
    void ResetTiming() noexcept
    {
        m_timing = StageTiming{};
    }

  private:
    SomeipParser             &m_parser;   ///< Non-owning view of the decoder.
    FeatureStreamer          &m_streamer; ///< Non-owning view of the extractor.
    const Normalizer         &m_norm;     ///< Non-owning view of the normalisation bounds.
    const IClassifier        &m_clf;      ///< Non-owning view of the inference engine.
    ISecurityEventDispatcher &m_sink;     ///< Non-owning view of the event destination.
    StageTiming               m_timing;   ///< Accumulated per-stage timings.
};

} // namespace ids

/** @}*/ // End of IdsSensorSensor
