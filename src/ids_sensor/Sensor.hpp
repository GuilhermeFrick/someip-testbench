#include <cstdint>

#include "src/ids_sensor/Classifier.hpp"
#include "src/ids_sensor/EventReporter.hpp"
#include "src/ids_sensor/FeatureStreamer.hpp"
#include "src/ids_sensor/Normalizer.hpp"
#include "src/ids_sensor/PacketSource.hpp"
#include "src/ids_sensor/SomeipParser.hpp"
#include "src/ids_sensor/types.hpp"

/** @addtogroup IdsSensorSensor Sensor composition
 *  @ingroup IdsSensor
 *  @{
 */

namespace ids
{

/**
 * @brief Accumulated time per pipeline stage, in microseconds.
 */
struct StageTiming
{
    double        parseUs    = 0.0; ///< Time spent in layered parsing.
    double        featureUs  = 0.0; ///< Time spent extracting features.
    double        classifyUs = 0.0; ///< Time spent in inference.
    double        decideUs   = 0.0; ///< Time spent deciding and reporting.
    std::uint64_t packets    = 0U;  ///< Packets processed.
    std::uint64_t events     = 0U;  ///< Security events reported.
};

/**
 * @brief Chains parser, extractor, normaliser, classifier and reporter.
 */
class Sensor final
{
  public:
    /**
     * @brief Wire the pipeline stages together.
     * @param[in] parser   Layered packet decoder.
     * @param[in] streamer Feature extractor, which carries the window state.
     * @param[in] norm     Normalisation bounds from training.
     * @param[in] clf      Inference engine to use.
     * @param[in] reporter Destination of the security events.
     * @return None.
     * @details Dependencies enter by reference: whoever builds the sensor decides which engine and
     *          which event sink to use. The sensor chooses neither, and owns neither.
     * @warning Every referenced stage must outlive the sensor.
     */
    Sensor(SomeipParser &parser, FeatureStreamer &streamer, const Normalizer &norm, const IClassifier &clf, IEventReporter &reporter);

    /**
     * @brief Process one frame end to end.
     * @param[in] frame Raw frame to process.
     * @return None.
     * @details Parses, extracts, normalises, infers and, when the predicted class is not
     *          ::ids::TrafficClass::Normal, reports the security event. Updates the stage timings.
     */
    void OnFrame(const Frame &frame);

    /**
     * @brief Consume a source until the end of its stream.
     * @param[in] source Packet source to drain.
     * @return None.
     * @details The SAME function serves PCAP replay and live capture, because the source is an
     *          interface.
     */
    void Run(IPacketSource &source);

    /**
     * @brief Accumulated stage timings.
     * @return Timings collected since construction or since the last ResetTiming().
     */
    const StageTiming &Timing() const
    {
        return m_timing;
    }

    /**
     * @brief Zero the accumulated stage timings.
     * @return None.
     */
    void ResetTiming()
    {
        m_timing = StageTiming{};
    }

  private:
    SomeipParser      &m_parser;   ///< Non-owning view of the decoder.
    FeatureStreamer   &m_streamer; ///< Non-owning view of the extractor.
    const Normalizer  &m_norm;     ///< Non-owning view of the normalisation bounds.
    const IClassifier &m_clf;      ///< Non-owning view of the inference engine.
    IEventReporter    &m_reporter; ///< Non-owning view of the event sink.
    StageTiming        m_timing;   ///< Accumulated per-stage timings.
};

} // namespace ids

/** @}*/ // End of IdsSensorSensor
